import { writeFileSync } from "node:fs";
import { SEED_ARTISTS } from "../lib/seed-data";
import { normalizeArtist } from "../lib/normalize";

const esc = (s: string) => s.replace(/'/g, "''");
const rows = SEED_ARTISTS.map(
  (a) =>
    `  ('${esc(a.name)}', '${esc(normalizeArtist(a.name))}', '${a.origin}', 'seed', ${a.favorite ? "true" : "false"})`,
);
const sql = `-- Starter artist list (generated by scripts/gen-seed-sql.ts). Safe to re-run.\ninsert into artists (name, name_normalized, origin, source, is_favorite) values\n${rows.join(",\n")}\non conflict (name_normalized) do nothing;\n`;
writeFileSync("db/seed.sql", sql);
console.log(`wrote ${rows.length} rows`);
